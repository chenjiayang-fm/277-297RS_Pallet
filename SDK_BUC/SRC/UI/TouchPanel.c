static uint8_t TouchPanel_ReadData(uint16_t *X, uint16_t *Y,uint8_t readmaxpoint)
{
	 uint8_t touch_buf[6] = {0};
	 uint8_t touchingSum=0;
	 uint8_t i=0;
	 bool temp;
	 temp = bTouchPanel_I2C_Read(0x814E, touch_buf);  //number of touch points
	 //if(temp == false)
	 	//printf("temp error!!!");
	 //printf("##################touch_buf[0] & 0x80 is %d\n",touch_buf[0] & 0x80);
 	 if(touch_buf[0] & 0x80)
	 {
		 touchingSum=(touch_buf[0] & 0x0F);
		 //printf("##################touchingSum is %d\n",touchingSum);
		 if(touchingSum> 0)
		 {	 
			 if(readmaxpoint<=1)
				 touchingSum=1;
			 
			 if(touchingSum==2)
			 {
				for(i=0;i<4;i++)
					bTouchPanel_I2C_Read(0x8150+i, touch_buf+i);
				*X = touch_buf[0]+touch_buf[1]*256;
				*Y = touch_buf[2]+touch_buf[3]*256;

				for(i=0;i<4;i++)
					bTouchPanel_I2C_Read(0x8158+i, touch_buf+i);
				*(X+1) = touch_buf[0]+touch_buf[1]*256;
				*(Y+1) = touch_buf[2]+touch_buf[3]*256;
			 }
			 else
			 {		
				for(i = 0;i<4;i++)
					bTouchPanel_I2C_Read(0x8150+i, touch_buf+i);
				*X = touch_buf[0]+touch_buf[1]*256;
				*Y = touch_buf[2]+touch_buf[3]*256;
			 }
			 touch_buf[0] = 0x00;
			 bTouchPanel_I2C_Write(0x814E,touch_buf[0]);
			 
			 return  touchingSum;
		 }
		 touch_buf[0] = 0x00;
		 bTouchPanel_I2C_Write(0x814E,touch_buf[0]);
		 *X = 0;
		 *Y = 0;
		 return FALSE;
	 }
	 *X = 0;
	 *Y = 0;
	 return FALSE;
}
uint16_t fabs_xy(uint16_t a, uint16_t b)
{
	if(a > b)
		return a-b;
	else
		return b-a;	
}

TouchGesture_t GetGesture(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
	uint16_t dx = 0, dy = 0;
	dx = fabs_xy(x0,x1);
	dy = fabs_xy(y0, y1);
	if((dx > 20) || (dy > 20))
	{
		if(dx > dy)
		{
			if(x0 > x1)
			{
				return TOUCH_TURNLEFT;
			}
			else
			{
				return TOUCH_TURNRIGHT;
			}
		}
		else
		{
			if(y0 > y1)
			{
				return TOUCH_TURNUP;
			}
			else
			{
				return TOUCH_TURNDOWN;
			}	
				
		}
	}
	
	return 	TOUCH_PRESS;
}

