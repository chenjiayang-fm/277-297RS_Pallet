//该函数一次往一个地址写一个字节
static bool bTouchPanel_I2C_Write(uint16_t ubAddress, uint8_t ubValue)
{
	uint8_t pBuf[3];
	
	pBuf[0] = (uint8_t)(ubAddress >> 8);
	pBuf[1] = (uint8_t)(ubAddress);
	pBuf[2] = ubValue;	
	
	//printd(DBG_ErrorLvl, "%s(0x%x):idx:0x%x%x, val:0x%x\n", __FUNCTION__, TouchPanel_I2C, pBuf[0], pBuf[1], ubValue);	

	if (TouchPanel_I2C != NULL)
		return bI2C_MasterProcess (TouchPanel_I2C, TOUCHPANEL_SLAVEADDR, &pBuf[0], 3, NULL, 0);
	else
		return false;
}
//该函数一次从一个地址读一个字节
static bool bTouchPanel_I2C_Read(uint16_t ubAddress, uint8_t *pValue)
{

	uint8_t pBuf[2];
	pBuf[0] = (uint8_t)(ubAddress >> 8);
	pBuf[1] = (uint8_t)(ubAddress);

	if (TouchPanel_I2C != NULL)
		return bI2C_MasterProcess (TouchPanel_I2C, TOUCHPANEL_SLAVEADDR	, &pBuf[0], 2, pValue, 1);
	else
		return false;
}

