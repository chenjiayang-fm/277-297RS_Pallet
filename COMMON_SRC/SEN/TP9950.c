//------------------------------------------------------------------------------
static void SEN_CheckStateThread(void const *argument)
{
    uint32_t ulTemp;
    uint8_t ubDoReSensorFlg = 0;
    uint8_t ubNoVideoCnt    = 0;

    while(1)
    {
		if(ubThreadFg == 0)
		{	
			SEN_SetStateChangeFlg(0);
			SEN_SetDetectVideoState(0);	
			if(ubSEN_GetDetectVideoState() != 1)
			{
				SEN_ReSensorInit();
				SEN_SetISPWindowSize();
				ubSEN_InitProcess();
				{
					BUF_Reset(BUF_SEN_1_YUV);
					ulTemp = ulBUF_GetSen1YuvFreeBuf();
					SEN_SetPathAddr(SENSOR_PATH1,ulTemp);
					SEN_UpdatePathAddr();
					osMessageReset(tSEN_ExtEventQueue);
				}
				if(sensor_state.ubVliadVideo == TP9950_ValidVideo)
				{	
					ubThreadFg 		= 1;
					ubTP9950_VdoChg = 0;
					SEN_SetDetectVideoState(1);
					SEN_SetStateChangeFlg(1);
				}
			} 
		}	
        else if(ubThreadFg == 1)
        {
			if(ubDoReSensorFlg == 0)
			{	
				//printf("<Type = %d> ",sensor_state.ubInputType);
				if(ubSEN_DetectState() == TP9950_NoVideo)
				{
					if(ubTP9950_VdoChg == 1)
					{
						ubNoVideoCnt = 2;
					}
					else
					{
						++ubNoVideoCnt;
					}		
					if(ubNoVideoCnt >= 2)
					{
						ubDoReSensorFlg = 1;
						ubNoVideoCnt	= 0;
						SEN_SetDetectVideoState(0);
					}
				}
				else
				{
					if(sensor_state.ubVliadVideo != SEN_ValidVideo)
					{
						ubDoReSensorFlg = 1;
						ubNoVideoCnt	= 0;
						SEN_SetDetectVideoState(0);
					}
					else
					{	
						ubNoVideoCnt = 0;
					}
				}
			}
			if(ubDoReSensorFlg)
			{
				if(ubTP9950_VdoChg == 1)
				{
					ubTP9950_VdoChg = 0;
					if(ubSEN_GetDetectVideoState() != 1)
					{
						SEN_ReSensorInit();
						SEN_SetISPWindowSize();
						ubSEN_InitProcess();
						{
							BUF_Reset(BUF_SEN_1_YUV);
							ulTemp = ulBUF_GetSen1YuvFreeBuf();
							SEN_SetPathAddr(SENSOR_PATH1,ulTemp);
							SEN_UpdatePathAddr();
							osMessageReset(tSEN_ExtEventQueue);
						}
						ubDoReSensorFlg = 0;
						if(sensor_state.ubVliadVideo == TP9950_ValidVideo)
						{	
							SEN_SetDetectVideoState(1);
						}
					} 
				}	
				else if(ubSEN_DetectState() == TP9950_ValidVideo)
				{
					if(ubSEN_GetDetectVideoState() != 1)
					{
						SEN_ReSensorInit();
						SEN_SetISPWindowSize();
						ubSEN_InitProcess();
						{
							BUF_Reset(BUF_SEN_1_YUV);
							ulTemp = ulBUF_GetSen1YuvFreeBuf();
							SEN_SetPathAddr(SENSOR_PATH1,ulTemp);
							SEN_UpdatePathAddr();
							osMessageReset(tSEN_ExtEventQueue);
						}
						ubDoReSensorFlg = 0;
						if(sensor_state.ubVliadVideo == TP9950_ValidVideo)
						{	
							SEN_SetDetectVideoState(1);
						}
					} 
				}
			}		
        } 
		osDelay(100);
    } 
}

