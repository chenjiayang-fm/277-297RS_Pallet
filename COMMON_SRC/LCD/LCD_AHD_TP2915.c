//------------------------------------------------------------------------------
void AHD_TP2915_Start(void)
{
    uint16_t uwDeviceID;
    uint8_t* pbBuf = (uint8_t*)&uwDeviceID;

    // Detect I2C Slave Address & Read Device ID
    /*
    	The I2C slave address should be detect by following manner whenever the
    	INT pin of TP2915 is pulled-up or leaving no-connection. There should be
    	a bug of TP2915.
    */
    ubAHD_TP2915_I2cSlaveAddr = AHD_TP2915_I2C_SLAVE_ADDR_NO_CONNECT;
    bAHD_TP2915_Read(0xFE, &pbBuf[1]);
    bAHD_TP2915_Read(0xFF, &pbBuf[0]);
    if(uwDeviceID != 0x2915)
    {
        ubAHD_TP2915_I2cSlaveAddr = AHD_TP2915_I2C_SLAVE_ADDR_PULL_UP;
        bAHD_TP2915_Read(0xFE, &pbBuf[1]);
        bAHD_TP2915_Read(0xFF, &pbBuf[0]);
        if(uwDeviceID != 0x2915)
        {
            printd(DBG_ErrorLvl, "This is not TP2915, ID = %X\n", uwDeviceID);
            return;
        }
    }
    printd(DBG_InfoLvl, "TP2915 Slave Address = 0x%02X\n", ubAHD_TP2915_I2cSlaveAddr << 1);

    bAHD_TP2915_Write(0x3A, 0x00);                                              //! Power up the DAC

    for(int i=0;i<256;i++)
        bAHD_TP2915_Write(i, ubAHD_TP2915_RegTable[i*AHD_TP2915_FORMAT_MAX + ubAHD_TP2915_OutputType]);
	
#if TP2915_DEBUG_EN
	#if ( TP2915_TEST_PATTERN_EN == 1 )
		bAHD_TP2915_Read(0x02, &pbBuf[0]);
		bAHD_TP2915_Write(0x02, pbBuf[0]|0x40);
	#endif
#endif
}
//------------------------------------------------------------------------------
void LCD_PixelPllSetting(void)
{
	float fPixelClock;
	float fFVCO;
    uint8_t ubFps;

    switch(ubAHD_TP2915_OutputType)
    {
        case AHD_TP2915_CVBS_NTSC:
            LCD->LCD_PCK_SPEED = 6;
            GLB->LCDPLL_FRA = 0x80000;
            ubFps = 30;
            break;
        case AHD_TP2915_CVBS_PAL:
            LCD->LCD_PCK_SPEED = 6;
            GLB->LCDPLL_FRA = 0x80000;
            ubFps = 25;
            break;
        case AHD_TP2915_AHD720P30:
            LCD->LCD_PCK_SPEED = 4;
            GLB->LCDPLL_FRA = 0x00000;
            ubFps = 30;
            break;
        case AHD_TP2915_AHD720P25:
            LCD->LCD_PCK_SPEED = 4;
            GLB->LCDPLL_FRA = 0x00000;
            ubFps = 25;
            break;
		case AHD_TP2915_TVI720P60:
			LCD->LCD_PCK_SPEED = 2;
            GLB->LCDPLL_FRA = 0x60000;
            ubFps = 60;
            break;
        case AHD_TP2915_TVI720P30:
            LCD->LCD_PCK_SPEED = 4;
            GLB->LCDPLL_FRA = 0x60000;
            ubFps = 30;
            break;
        case AHD_TP2915_TVI720P25:
            LCD->LCD_PCK_SPEED = 4;
            GLB->LCDPLL_FRA = 0x60000;
            ubFps = 25;
            break;
        case AHD_TP2915_AHD1080P30:
        case AHD_TP2915_TVI1080P30:
            ubFps = 30;
            LCD->LCD_PCK_SPEED = 2;
            GLB->LCDPLL_FRA = 0x60000;
            break;
        case AHD_TP2915_AHD1080P25:
        case AHD_TP2915_TVI1080P25:
            ubFps = 25;
            LCD->LCD_PCK_SPEED = 2;
            GLB->LCDPLL_FRA = 0x60000;
            break;
        default:
            break;
    }

	//! Calculation Pixel Clock
	switch (LCD->LCD_MODE)
	{
		case LCD_DE:
			fPixelClock = ((float)ubFps) * (LCD->LCD_HO_SIZE + LCD->LCD_HT_DM_SIZE + LCD->LCD_HT_START) *
								   (LCD->LCD_VO_SIZE + LCD->LCD_VT_DM_SIZE + LCD->LCD_VT_START) / 1000000;
            GLB->LCDPLL_INT = 12;
			break;
		case LCD_BT656_BT601:
            GLB->LCDPLL_INT = 13;
            fPixelClock = 27.0000;
			break;
		default:
			break;
	}

	GLB->LCDPLL_CK_SEL = 2;
	//! LCD PLL
	if (!GLB->LCDPLL_PD_N)
	{
		GLB->LCDPLL_LDO_EN = 1;
		GLB->LCDPLL_PD_N = 1;
		TIMER_Delay_us(400);
		GLB->LCDPLL_SDM_EN = 1;
		TIMER_Delay_us(1);
	}
	TIMER_Delay_us(1);
	GLB->LCDPLL_INT_FRA_VLD = 1;
	TIMER_Delay_us(1);
	//! LCD Controller rate
	GLB->LCD_RATE = 1;

	if (GLB->LCDPLL_CK_SEL == 0)
		fFVCO = fPixelClock * LCD->LCD_PCK_SPEED * 6;
	else if (GLB->LCDPLL_CK_SEL == 1)
		fFVCO = fPixelClock * LCD->LCD_PCK_SPEED * 2;
	else
		fFVCO = fPixelClock * LCD->LCD_PCK_SPEED * 1;

	if ((fFVCO < 148.3) || (fFVCO > 165)) { //range:148.3M ~ 165M
		printd(DBG_ErrorLvl, "fFVCO=%f MHz,Change PLL pls!\n", fFVCO);
	}
}
